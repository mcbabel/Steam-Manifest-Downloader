const INI_HEADER: &str = "# Generated by Steam Manifest Downloader.\n# Edit these settings via the in-app emulator step. Any keys not managed\n# here will be overwritten on re-apply.\n\n";

fn bool_to_ini(b: bool) -> &'static str {
    if b { "1" } else { "0" }
}

fn ini_from_bool(s: &str) -> Option<bool> {
    match s.trim() {
        "1" | "true" | "yes" | "on" => Some(true),
        "0" | "false" | "no" | "off" => Some(false),
        _ => None,
    }
}

fn parse_ini_sections(text: &str) -> std::collections::HashMap<String, std::collections::HashMap<String, String>> {
    let mut out: std::collections::HashMap<String, std::collections::HashMap<String, String>> =
        std::collections::HashMap::new();
    let mut current: Option<String> = None;
    for raw in text.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }
        if line.starts_with('[') && line.ends_with(']') {
            current = Some(line[1..line.len() - 1].trim().to_string());
            continue;
        }
        let Some(section) = current.as_ref() else { continue };
        let Some(eq) = line.find('=') else { continue };
        let key = line[..eq].trim().to_string();
        let val = line[eq + 1..].trim().to_string();
        out.entry(section.clone()).or_default().insert(key, val);
    }
    out
}

