    pub fn write_to_dir(&self, dir: &Path) -> Result<(), String> {
        fs::create_dir_all(dir).map_err(|e| format!("create steam_settings: {}", e))?;
        let write_or_remove = |name: &str, content: String| -> Result<(), String> {
            let path = dir.join(name);
            if content.trim().is_empty() {
                let _ = fs::remove_file(&path);
                return Ok(());
            }
            fs::write(&path, content).map_err(|e| format!("write {}: {}", name, e))
        };
        write_or_remove("configs.user.ini", self.render_user_ini())?;
        write_or_remove("configs.main.ini", self.render_main_ini())?;
        write_or_remove("configs.overlay.ini", self.render_overlay_ini())?;
        Ok(())
    }

