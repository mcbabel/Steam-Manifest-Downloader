#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Platform {
    Windows,
    Linux,
}

impl Platform {
    fn asset_name(self) -> &'static str {
        match self {
            Platform::Windows => "emu-win-release-vs26.7z",
            Platform::Linux => "emu-linux-release.tar.bz2",
        }
    }
    fn asset_match(
        self,
    ) -> (
        &'static str,
        &'static str,
        &'static [&'static str],
        &'static [&'static str],
    ) {
        match self {
            Platform::Windows => ("win", ".7z", &["release"], &["debug"]),
            Platform::Linux => ("linux", ".tar.bz2", &["release"], &["debug"]),
        }
    }
    pub fn cache_subdir(self) -> &'static str {
        match self {
            Platform::Windows => "windows",
            Platform::Linux => "linux",
        }
    }
    fn emu_filename(self, x64: bool) -> &'static str {
        match (self, x64) {
            (Platform::Windows, true) => "steam_api64.dll",
            (Platform::Windows, false) => "steam_api.dll",
            (Platform::Linux, _) => "libsteam_api.so",
        }
    }
}

