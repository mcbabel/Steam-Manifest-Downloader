pub fn generate_interfaces(dll_bytes: &[u8]) -> Result<String, String> {
    let mut out = String::new();
    let mut total: usize = 0;
    for patt in INTERFACE_PATTERNS {
        let re = Regex::new(patt).map_err(|e| format!("bad pattern '{}': {}", patt, e))?;
        let mut matches: Vec<Vec<u8>> = re
            .find_iter(dll_bytes)
            .map(|m| m.as_bytes().to_vec())
            .collect();

        if *patt == r"SteamClient\d+" && matches.len() > 1 {
            let has_017 = matches.iter().any(|m| m == b"SteamClient017");
            if has_017 {
                matches.retain(|m| m == b"SteamClient017");
            }
        }

        for m in matches {
            if let Ok(s) = std::str::from_utf8(&m) {
                out.push_str(s);
                out.push('\n');
                total += 1;
            }
        }
    }
    if total == 0 {
        return Err("No Steam interfaces found in the binary".into());
    }
    Ok(out)
}

fn generate_interfaces_from_file(target: &Path) -> Result<String, String> {
    let bytes = fs::read(target).map_err(|e| format!("read {}: {}", target.display(), e))?;
    generate_interfaces(&bytes)
}

pub fn apply_replacement(
    target: &Path,
    platform_cache: &Path,
    variant: Variant,
    platform: Platform,
    x64: bool,
    app_id: &str,
    installed_app_ids: &[String],
    emu_settings: Option<&EmuSettings>,
    dlcs: Option<&[(String, String)]>,
) -> ReplaceResult {
    let mut result = ReplaceResult {
        path: target.to_string_lossy().to_string(),
        backup_path: None,
        success: false,
        error: None,
        fail_class: None,
        dlc_count: None,
    };
    crate::dlog!(
        "emu",
        "apply start target={} platform={:?} arch={} variant={:?}",
        target.display(),
        platform,
        if x64 { "x64" } else { "x32" },
        variant
    );
    match apply_to_target(
        target,
        platform_cache,
        variant,
        platform,
        x64,
        app_id,
        installed_app_ids,
        emu_settings,
        dlcs,
        &mut result,
    ) {
        Ok(()) => {
            result.success = true;
            crate::dlog!("emu", "apply ok target={}", target.display());
        }
        Err((class, e)) => {
            crate::dlog!(
                "emu",
                "apply FAILED target={} class={} reason={}",
                target.display(),
                class,
                e
            );
            result.fail_class = Some(class.to_string());
            result.error = Some(e);
        }
    }
    result
}

fn apply_to_target(
    target: &Path,
    platform_cache: &Path,
    variant: Variant,
    platform: Platform,
    x64: bool,
    app_id: &str,
    installed_app_ids: &[String],
    emu_settings: Option<&EmuSettings>,
    dlcs: Option<&[(String, String)]>,
    result: &mut ReplaceResult,
) -> Result<(), TargetError> {
    let emu_dll = dll_source(platform_cache, variant, x64, platform)
        .map_err(|e| (fail::EMU_BINARY_MISSING, e))?;
    crate::dlog!("emu", "emulator binary resolved: {}", emu_dll.display());

    let interfaces_source = interfaces_source_for(target);
    crate::dlog!(
        "emu",
        "reading interfaces from {} (backup={})",
        interfaces_source.display(),
        interfaces_source != target
    );
    let interfaces = generate_interfaces_from_file(&interfaces_source)
        .map_err(|e| (fail::INTERFACES_FAILED, format!("generate_interfaces failed: {}", e)))?;

    let backup = backup_path_for(target);
    if backup.exists() {
        crate::dlog!("emu", "backup already present: {}", backup.display());
    } else {
        fs::copy(target, &backup)
            .map_err(|e| (fail::BACKUP_FAILED, format!("backup original: {}", e)))?;
        crate::dlog!("emu", "backup created: {}", backup.display());
    }
    result.backup_path = Some(backup.to_string_lossy().to_string());

    fs::copy(&emu_dll, target)
        .map_err(|e| (fail::COPY_FAILED, format!("copy emulator binary: {}", e)))?;

    let parent = target
        .parent()
        .ok_or((fail::NO_PARENT_DIR, "target has no parent dir".to_string()))?;
    let settings_dir = parent.join("steam_settings");
    fs::create_dir_all(&settings_dir)
        .map_err(|e| (fail::SETTINGS_WRITE_FAILED, format!("create steam_settings: {}", e)))?;

    fs::write(settings_dir.join("steam_interfaces.txt"), interfaces).map_err(|e| {
        (fail::SETTINGS_WRITE_FAILED, format!("write steam_interfaces.txt: {}", e))
    })?;
    fs::write(settings_dir.join("steam_appid.txt"), app_id.trim()).map_err(|e| {
        (fail::SETTINGS_WRITE_FAILED, format!("write steam_appid.txt: {}", e))
    })?;
    if !installed_app_ids.is_empty() {
        let joined = installed_app_ids
            .iter()
            .map(|s| s.trim())
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join("\n");
        fs::write(settings_dir.join("installed_app_ids.txt"), joined).map_err(|e| {
            (fail::SETTINGS_WRITE_FAILED, format!("write installed_app_ids.txt: {}", e))
        })?;
    }

    if let Some(list) = dlcs {
        fs::write(settings_dir.join("configs.app.ini"), render_app_ini(list)).map_err(|e| {
            (fail::SETTINGS_WRITE_FAILED, format!("write configs.app.ini: {}", e))
        })?;
        result.dlc_count = Some(list.len());
    }

    if let Some(s) = emu_settings {
        s.write_to_dir(&settings_dir)
            .map_err(|e| (fail::SETTINGS_WRITE_FAILED, format!("write emu settings: {}", e)))?;
    }
    Ok(())
}

pub fn read_emu_settings_for_target(target: &Path) -> Result<EmuSettings, String> {
    let parent = target
        .parent()
        .ok_or_else(|| "target has no parent dir".to_string())?;
    let settings_dir = parent.join("steam_settings");
    Ok(EmuSettings::read_from_dir(&settings_dir))
}

pub fn write_emu_settings_for_target(target: &Path, settings: &EmuSettings) -> Result<(), String> {
    let parent = target
        .parent()
        .ok_or_else(|| "target has no parent dir".to_string())?;
    if !parent.exists() {
        return Err(format!("game folder not found: {}", parent.display()));
    }
    let settings_dir = parent.join("steam_settings");
    fs::create_dir_all(&settings_dir).map_err(|e| format!("create steam_settings: {}", e))?;
    settings.write_to_dir(&settings_dir)
}

pub fn revert_replacement(target: &Path) -> Result<(), TargetError> {
    if let Some(parent) = target.parent() {
        if !parent.exists() {
            return Err((
                fail::FOLDER_MISSING,
                format!("game folder not found: {}", parent.display()),
            ));
        }
    }
    let backup = backup_path_for(target);
    if !backup.exists() {
        return Err((
            fail::NO_BACKUP,
            format!("no backup found at {}", backup.display()),
        ));
    }
    fs::copy(&backup, target)
        .map_err(|e| (fail::RESTORE_FAILED, format!("restore from backup: {}", e)))?;
    let _ = fs::remove_file(&backup);
    if let Some(parent) = target.parent() {
        let settings_dir = parent.join("steam_settings");
        let _ = fs::remove_file(settings_dir.join("steam_interfaces.txt"));
        let _ = fs::remove_file(settings_dir.join("steam_appid.txt"));
        let _ = fs::remove_file(settings_dir.join("installed_app_ids.txt"));
        let _ = fs::remove_file(settings_dir.join("configs.app.ini"));
        let _ = fs::remove_dir(&settings_dir);
    }
    Ok(())
}

fn interfaces_source_for(target: &Path) -> PathBuf {
    let backup = backup_path_for(target);
    if backup.exists() {
        backup
    } else {
        target.to_path_buf()
    }
}

fn backup_path_for(target: &Path) -> PathBuf {
    let mut p = target.as_os_str().to_owned();
    p.push(".steam.bak");
    PathBuf::from(p)
}

