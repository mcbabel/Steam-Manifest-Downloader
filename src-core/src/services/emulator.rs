fn render_sections(sections: &[(String, Vec<(String, String)>)]) -> String {
    if sections.is_empty() {
        return String::new();
    }
    let mut out = String::from(INI_HEADER);
    for (i, (name, kvs)) in sections.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        out.push('[');
        out.push_str(name);
        out.push_str("]\n");
        for (k, v) in kvs {
            out.push_str(k);
            out.push('=');
            out.push_str(v);
            out.push('\n');
        }
    }
    out
}

fn cache_root(app_data_dir: &Path) -> PathBuf {
    app_data_dir.join("gbe_fork_cache")
}

fn vs_number(name: &str) -> Option<u32> {
    let lower = name.to_lowercase();
    let mut best: Option<u32> = None;
    let mut search = lower.as_str();
    while let Some(pos) = search.find("vs") {
        let rest = &search[pos + 2..];
        let digits: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
        if let Ok(n) = digits.parse::<u32>() {
            best = Some(best.map_or(n, |b| b.max(n)));
        }
        search = rest;
    }
    best
}

fn pick_asset<'a>(
    assets: &'a [serde_json::Value],
    name: &str,
    keyword: &str,
    extension: &str,
    required: &[&str],
    excluded: &[&str],
) -> Result<&'a serde_json::Value, String> {
    let mut candidates: Vec<&serde_json::Value> = assets
        .iter()
        .filter(|a| {
            a.get("name").and_then(|v| v.as_str()).is_some_and(|n| {
                let lower = n.to_lowercase();
                lower.contains(keyword)
                    && lower.ends_with(extension)
                    && required.iter().all(|r| lower.contains(r))
                    && !excluded.iter().any(|x| lower.contains(x))
            })
        })
        .collect();
    candidates.sort_by_key(|a| {
        let n = a.get("name").and_then(|v| v.as_str()).and_then(vs_number);
        (n.is_none(), n.map(std::cmp::Reverse))
    });
    if let Some(a) = candidates.iter().find(|a| {
        a.get("name")
            .and_then(|v| v.as_str())
            .and_then(vs_number)
            .is_some()
    }) {
        return Ok(a);
    }
    if let Some(a) = assets
        .iter()
        .find(|a| a.get("name").and_then(|v| v.as_str()) == Some(name))
    {
        return Ok(a);
    }
    if let Some(a) = candidates.into_iter().next() {
        return Ok(a);
    }
    let available: Vec<String> = assets
        .iter()
        .filter_map(|a| {
            a.get("name")
                .and_then(|v| v.as_str())
                .map(str::to_string)
        })
        .collect();
    Err(format!(
        "Asset {} not present in release (available: {})",
        name,
        if available.is_empty() {
            "none".to_string()
        } else {
            available.join(", ")
        }
    ))
}

#[derive(Debug, Deserialize)]
struct BundledRelease {
    tag: String,
    #[serde(default)]
    published_at: String,
    windows: String,
    linux: String,
}

fn bundled_release_info(app_data_dir: &Path) -> Option<ReleaseInfo> {
    let manifest = crate::paths::bundled_file(&["gbe_fork", "release.json"])?;
    let dir = manifest.parent()?.to_path_buf();
    let release: BundledRelease = serde_json::from_slice(&fs::read(&manifest).ok()?).ok()?;
    let windows = dir.join(&release.windows);
    let linux = dir.join(&release.linux);
    let windows_size = fs::metadata(&windows).ok().filter(|m| m.is_file())?.len();
    let linux_size = fs::metadata(&linux).ok().filter(|m| m.is_file())?.len();
    let root = cache_root(app_data_dir).join(&release.tag);
    Some(ReleaseInfo {
        windows_cached: root
            .join(Platform::Windows.cache_subdir())
            .join(".extracted")
            .exists(),
        linux_cached: root
            .join(Platform::Linux.cache_subdir())
            .join(".extracted")
            .exists(),
        tag: release.tag,
        published_at: release.published_at,
        windows_url: windows.to_string_lossy().to_string(),
        windows_size,
        linux_url: linux.to_string_lossy().to_string(),
        linux_size,
        cache_root: root.to_string_lossy().to_string(),
        bundled: true,
    })
}

pub async fn fetch_release_info(client: &Client, app_data_dir: &Path) -> Result<ReleaseInfo, String> {
    if let Some(info) = bundled_release_info(app_data_dir) {
        return Ok(info);
    }
    let resp = client
        .get(RELEASES_API)
        .header("User-Agent", USER_AGENT)
        .header("Accept", "application/vnd.github+json")
        .timeout(Duration::from_secs(30))
        .send()
        .await
        .map_err(|e| format!("GitHub fetch failed: {}", e))?;

    if !resp.status().is_success() {
        return Err(format!("GitHub returned HTTP {}", resp.status()));
    }

    let body: serde_json::Value = resp
        .json()
        .await
        .map_err(|e| format!("GitHub JSON parse failed: {}", e))?;

    let tag = body
        .get("tag_name")
        .and_then(|v| v.as_str())
        .ok_or("Missing tag_name in release info")?
        .to_string();
    let published_at = body
        .get("published_at")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string();

    let assets = body
        .get("assets")
        .and_then(|v| v.as_array())
        .ok_or("Missing assets array")?;

    let pick = |platform: Platform| -> Result<(String, u64), String> {
        let name = platform.asset_name();
        let (keyword, extension, required, excluded) = platform.asset_match();
        let a = pick_asset(assets, name, keyword, extension, required, excluded)?;
        let url = a
            .get("browser_download_url")
            .and_then(|v| v.as_str())
            .ok_or("Asset has no browser_download_url")?
            .to_string();
        let size = a.get("size").and_then(|v| v.as_u64()).unwrap_or(0);
        Ok((url, size))
    };

    let (windows_url, windows_size) = pick(Platform::Windows)?;
    let (linux_url, linux_size) = pick(Platform::Linux)?;

    let root = cache_root(app_data_dir).join(&tag);
    let windows_cached = root.join(Platform::Windows.cache_subdir()).join(".extracted").exists();
    let linux_cached = root.join(Platform::Linux.cache_subdir()).join(".extracted").exists();

    Ok(ReleaseInfo {
        tag,
        published_at,
        windows_url,
        windows_size,
        linux_url,
        linux_size,
        windows_cached,
        linux_cached,
        cache_root: root.to_string_lossy().to_string(),
        bundled: false,
    })
}

pub fn platform_cached(info: &ReleaseInfo, platform: Platform) -> bool {
    PathBuf::from(&info.cache_root)
        .join(platform.cache_subdir())
        .join(".extracted")
        .exists()
}

fn prune_keep(name: &str) -> bool {
    let lower = name.to_lowercase();
    lower == ".extracted"
        || lower.ends_with(".dll")
        || lower.ends_with(".so")
        || lower.contains(".so.")
}

fn prune_platform_dir(dir: &Path) {
    for entry in WalkDir::new(dir)
        .min_depth(1)
        .contents_first(true)
        .into_iter()
        .flatten()
    {
        let path = entry.path();
        if path.is_file() {
            let keep = path
                .file_name()
                .and_then(|n| n.to_str())
                .is_some_and(prune_keep);
            if !keep {
                let _ = fs::remove_file(path);
            }
        } else if path != dir {
            let _ = fs::remove_dir(path);
        }
    }
}

pub async fn ensure_cached(
    client: &Client,
    info: &ReleaseInfo,
    platform: Platform,
    on_progress: impl Fn(u64, u64) + Send + Sync,
) -> Result<PathBuf, String> {
    let platform_dir = PathBuf::from(&info.cache_root).join(platform.cache_subdir());
    let extracted_marker = platform_dir.join(".extracted");
    if extracted_marker.exists() {
        prune_platform_dir(&platform_dir);
        return Ok(platform_dir);
    }

    fs::create_dir_all(&platform_dir).map_err(|e| format!("create cache dir: {}", e))?;
    let asset_name = platform.asset_name();
    let asset_url = match platform {
        Platform::Windows => &info.windows_url,
        Platform::Linux => &info.linux_url,
    };
    let archive_path = platform_dir.join(asset_name);

    if !archive_path.exists() && info.bundled {
        fs::copy(asset_url, &archive_path)
            .map_err(|e| format!("copy bundled archive {}: {}", asset_url, e))?;
        let size = fs::metadata(&archive_path).map(|m| m.len()).unwrap_or(0);
        on_progress(size, size);
    }
    if !archive_path.exists() {
        let mut resp = client
            .get(asset_url)
            .header("User-Agent", USER_AGENT)
            .timeout(Duration::from_secs(600))
            .send()
            .await
            .map_err(|e| format!("download failed: {}", e))?;
        if !resp.status().is_success() {
            return Err(format!("download returned HTTP {}", resp.status()));
        }
        let total = match platform {
            Platform::Windows => info.windows_size,
            Platform::Linux => info.linux_size,
        };
        let tmp_path = platform_dir.join(format!("{}.part", asset_name));
        {
            let mut file =
                BufWriter::new(File::create(&tmp_path).map_err(|e| format!("create archive: {}", e))?);
            let mut downloaded: u64 = 0;
            let mut next_emit_at: u64 = 1024 * 1024;
            while let Some(chunk) = resp.chunk().await.map_err(|e| format!("chunk: {}", e))? {
                file.write_all(&chunk).map_err(|e| format!("write archive: {}", e))?;
                downloaded += chunk.len() as u64;
                if downloaded >= next_emit_at {
                    next_emit_at += 1024 * 1024;
                    on_progress(downloaded, total);
                }
            }
            file.flush().map_err(|e| format!("flush archive: {}", e))?;
            on_progress(downloaded, total);
        }
        fs::rename(&tmp_path, &archive_path).map_err(|e| format!("finalize archive: {}", e))?;
    }

    if let Err(e) = extract_archive(&archive_path, &platform_dir, platform) {
        if e.starts_with("AV_BLOCKED") {
            let _ = fs::remove_file(&archive_path);
        }
        return Err(e);
    }
    let _ = fs::remove_file(&archive_path);
    prune_platform_dir(&platform_dir);
    fs::write(&extracted_marker, info.tag.as_bytes())
        .map_err(|e| format!("write extracted marker: {}", e))?;

    Ok(platform_dir)
}

fn extract_archive(archive: &Path, dst: &Path, platform: Platform) -> Result<(), String> {
    match platform {
        Platform::Linux => extract_tar_bz2(archive, dst),
        Platform::Windows => extract_7z(archive, dst),
    }
}

fn extract_tar_bz2(archive: &Path, dst: &Path) -> Result<(), String> {
    let file = File::open(archive).map_err(|e| format!("open archive: {}", e))?;
    let mut decoder = BzDecoder::new(BufReader::new(file));
    let mut tmp = Vec::with_capacity(64 * 1024 * 1024);
    decoder
        .read_to_end(&mut tmp)
        .map_err(|e| format!("bzip2 decompress: {}", e))?;
    let mut tar = Archive::new(io::Cursor::new(tmp));
    tar.unpack(dst).map_err(|e| format!("tar unpack: {}", e))?;
    Ok(())
}

fn extract_7z(archive: &Path, dst: &Path) -> Result<(), String> {
    sevenz_rust::decompress_file(archive, dst).map_err(|e| {
        let msg = e.to_string();
        if is_antivirus_block(&msg) {
            format!("AV_BLOCKED: {}", msg)
        } else {
            format!("7z decompress: {}", msg)
        }
    })
}

fn is_antivirus_block(msg: &str) -> bool {
    let lower = msg.to_lowercase();
    msg.contains("code: 225")
        || lower.contains("virus")
        || lower.contains("unerwünschte software")
        || lower.contains("unwanted software")
}

fn arch_dirs(x64: bool) -> &'static [&'static str] {
    if x64 {
        &["x64"]
    } else {
        &["x86", "x32"]
    }
}

fn build_trees() -> &'static [&'static str] {
    &["release", "debug"]
}

pub fn dll_source(
    platform_cache: &Path,
    variant: Variant,
    x64: bool,
    platform: Platform,
) -> Result<PathBuf, String> {
    let filename = platform.emu_filename(x64);
    let mut tried = Vec::new();
    for tree in build_trees() {
        let root = platform_cache.join(tree).join(variant.folder());
        for dir in arch_dirs(x64) {
            let p = root.join(dir).join(filename);
            if p.exists() {
                return Ok(p);
            }
            tried.push(p.display().to_string());
        }
    }
    Err(format!("emulator binary not found, tried: {}", tried.join(", ")))
}

pub fn scan_game_dir(game_dir: &Path) -> Vec<ScannedFile> {
    let mut out = Vec::new();
    if !game_dir.exists() {
        return out;
    }
    for entry in WalkDir::new(game_dir).follow_links(false).into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
        let (platform, arch) = if name == "steam_api64.dll" {
            (Platform::Windows, "x64")
        } else if name == "steam_api.dll" {
            (Platform::Windows, "x32")
        } else if name == "libsteam_api.so" {
            (Platform::Linux, detect_so_arch(entry.path()))
        } else {
            continue;
        };
        let is_patched = backup_path_for(entry.path()).exists();
        out.push(ScannedFile {
            path: entry.path().to_string_lossy().to_string(),
            platform,
            arch: arch.to_string(),
            is_patched,
        });
    }
    out
}

fn detect_so_arch(path: &Path) -> &'static str {
    let Ok(mut file) = File::open(path) else {
        return "x64";
    };
    let mut header = [0u8; 5];
    if file.read_exact(&mut header).is_err() {
        return "x64";
    }
    if &header[..4] != b"\x7fELF" {
        return "x64";
    }
    match header[4] {
        1 => "x32",
        2 => "x64",
        _ => "x64",
    }
}

